import 'package:flutter/material.dart';

class SubscriptionCatalogItem {
  final String id;
  final String nameEn;
  final String nameAr;
  final double cost;
  final IconData icon;
  final String category;
  final String categoryEn;
  final String categoryAr;
  bool isSelected;
  bool isCustom;

  SubscriptionCatalogItem({
    required this.id,
    required this.nameEn,
    required this.nameAr,
    required this.cost,
    required this.icon,
    required this.category,
    required this.categoryEn,
    required this.categoryAr,
    this.isSelected = false,
    this.isCustom = false,
  });

  String displayName(String lang) => lang == 'ar' ? nameAr : nameEn;
  String displayCategory(String lang) => lang == 'ar' ? categoryAr : categoryEn;

  Map<String, dynamic> toMap() {
    return {
      'id': id,
      'name': nameEn,
      'nameAr': nameAr,
      'cost': cost,
      'icon': icon,
      'selected': isSelected,
      'category': category,
      'isCustom': isCustom,
    };
  }

  SubscriptionCatalogItem copyWith({
    bool? isSelected,
    double? cost,
    String? nameEn,
    String? nameAr,
  }) {
    return SubscriptionCatalogItem(
      id: id,
      nameEn: nameEn ?? this.nameEn,
      nameAr: nameAr ?? this.nameAr,
      cost: cost ?? this.cost,
      icon: icon,
      category: category,
      categoryEn: categoryEn,
      categoryAr: categoryAr,
      isSelected: isSelected ?? this.isSelected,
      isCustom: isCustom,
    );
  }
}

